export const VIETNAM_CHAT_ROOM_MAP = new Map<string, VietnamChatRoomDef>(
  VIETNAM_CHAT_ROOMS.map((room) => [room.id, room])
);

export function resolveVietnamChatRoomId(roomId: string): string {
  const clean = roomId.trim().toLowerCase();
  if (VIETNAM_CHAT_ROOM_MAP.has(clean)) return clean;
  if (LEGACY_PROVINCE_ALIASES[clean]) return LEGACY_PROVINCE_ALIASES[clean];
  return 'nhac-tre';
}

export function getVietnamChatRoom(roomId: string): VietnamChatRoomDef {
  return VIETNAM_CHAT_ROOM_MAP.get(resolveVietnamChatRoomId(roomId)) ?? VIETNAM_CHAT_ROOMS[0];
}
